import { useEffect, useMemo, useRef, useState } from 'react';
import { Icon } from '../components/Icon';
import { Badge, Button, Field, InfoTip, PageHeader, SimTag } from '../components/ui';
import { useLocation } from '../lib/router';
import { validateTopic } from '../services/mqtt/topics';
import { clearMessages, publishRaw, useRuntime } from '../state/runtime';
import { useStudio } from '../state/studio';
import { toast } from '../state/ui';
import type { MqttMessage } from '../types/models';
import { clock, cn, prettyJson } from '../utils';

type Dir = 'all' | 'in' | 'out';

const KIND_LABEL: Record<MqttMessage['kind'], string> = { telemetry: 'Telemetry', command: 'Command', ack: 'Ack', availability: 'Availability' };

export function ConsolePage() {
  const simulatedMode = useRuntime((s) => (s.status ? s.status.mode === 'simulated' : true));
  const { query } = useLocation();
  const live = useRuntime((s) => s.messages);
  const devices = useStudio((s) => s.devices);
  const commandTopics = useStudio((s) => s.variables.filter((v) => v.commandTopic).map((v) => v.commandTopic!));
  const [paused, setPaused] = useState(false);
  const [frozen, setFrozen] = useState<MqttMessage[] | null>(null);
  const [q, setQ] = useState('');
  const [device, setDevice] = useState(query.get('device') ?? 'all');
  const [topic, setTopic] = useState('all');
  const [dir, setDir] = useState<Dir>('all');
  const [hideAvail, setHideAvail] = useState(false);
  const [selected, setSelected] = useState<string | null>(null);
  const [pubTopic, setPubTopic] = useState('');
  const [pubPayload, setPubPayload] = useState('{"value": true}');
  const [pubErr, setPubErr] = useState('');
  const listRef = useRef<HTMLDivElement | null>(null);

  useEffect(() => { if (query.get('device')) setDevice(query.get('device')!); }, [query.get('device')]);
  const source = paused && frozen ? frozen : live;
  const newSince = paused && frozen ? live.length - frozen.length : 0;

  const topicOptions = useMemo(() => {
    const set = new Set<string>();
    for (const m of live) {
      const parts = m.topic.split('/');
      set.add(parts.length > 3 ? `${parts[3]}${parts[4] ? '/' + parts[4] : ''}` : m.topic);
    }
    return Array.from(set).sort();
  }, [live.length]);

  const rows = useMemo(() => {
    const query2 = q.trim().toLowerCase();
    return source
      .filter((m) => (device === 'all' || m.deviceId === device)
        && (dir === 'all' || m.direction === dir)
        && (!hideAvail || m.kind !== 'availability')
        && (topic === 'all' || m.topic.includes(`/${topic}`))
        && (!query2 || m.topic.toLowerCase().includes(query2) || m.payload.toLowerCase().includes(query2)))
      .slice(-300)
      .reverse();
  }, [source, device, dir, topic, q, hideAvail]);

  const sel = source.find((m) => m.id === selected) ?? null;
  const devName = (id: string | null) => devices.find((d) => d.id === id)?.name ?? '—';
  const inCount = source.filter((m) => m.direction === 'in').length;

  return (
    <main className="page console-page" id="main">
      <PageHeader kicker="DEBUG" title="MQTT" serif="console"
        actions={
          <>
            <Button icon={paused ? 'LuPlay' : 'LuPause'} variant={paused ? 'primary' : 'outline'} onClick={() => { if (paused) { setPaused(false); setFrozen(null); } else { setFrozen(live); setPaused(true); } }}>
              {paused ? `Resume${newSince > 0 ? ` (${newSince} new)` : ''}` : 'Pause feed'}
            </Button>
            <Button icon="LuTrash2" variant="ghost" onClick={() => { clearMessages(); setFrozen(null); setSelected(null); }}>Clear</Button>
          </>
        }>
        Every message between your devices and dashboards, streamed live from the Kokoon server. {simulatedMode && <><SimTag /> Traffic is generated by the server’s demo simulator.</>}
      </PageHeader>

      <div className="console-filters">
        <div className="search grow">
          <Icon name="LuSearch" size={15} />
          <input id="console-search" className="input-bare" placeholder="Search topic or payload" value={q} onChange={(e) => setQ(e.target.value)} aria-label="Search messages" />
        </div>
        <select className="input input-sm" value={device} onChange={(e) => setDevice(e.target.value)} aria-label="Filter by device">
          <option value="all">All devices</option>
          {devices.map((d) => <option key={d.id} value={d.id}>{d.name}</option>)}
        </select>
        <select className="input input-sm" value={topic} onChange={(e) => setTopic(e.target.value)} aria-label="Filter by topic">
          <option value="all">All topics</option>
          {topicOptions.map((t) => <option key={t} value={t}>{t}</option>)}
        </select>
        <div className="segmented" role="radiogroup" aria-label="Direction">
          {([['all', 'All'], ['in', '↓ Incoming'], ['out', '↑ Outgoing']] as const).map(([v, l]) => (
            <button key={v} type="button" role="radio" aria-checked={dir === v} className={cn(dir === v && 'is-active')} onClick={() => setDir(v)}>{l}</button>
          ))}
        </div>
        <label className="check small"><input type="checkbox" checked={hideAvail} onChange={(e) => setHideAvail(e.target.checked)} /> Hide availability</label>
      </div>

      <div className="console-grid">
        <section className="console-list cut-card" aria-label="Messages">
          <div className="console-head-row">
            <span>TIME</span><span>DIR</span><span>DEVICE</span><span>TOPIC</span><span>PAYLOAD</span><span>TYPE</span><span>STATUS</span>
          </div>
          <div className="console-rows" ref={listRef}>
            {rows.map((m) => (
              <button key={m.id} type="button" className={cn('console-row', m.direction === 'in' ? 'is-in' : 'is-out', selected === m.id && 'is-selected')} onClick={() => setSelected(m.id)}>
                <span className="tabnum">{clock(m.at, true)}</span>
                <span className="c-dir">{m.direction === 'in' ? '↓ IN' : '↑ OUT'}</span>
                <span className="c-dev">{devName(m.deviceId)}</span>
                <code className="c-topic">{m.topic}</code>
                <code className="c-payload">{m.payload}</code>
                <span className="c-kind">{KIND_LABEL[m.kind]}</span>
                <span className={cn('msg-status', `st-${m.status}`)}>{m.status}</span>
              </button>
            ))}
            {!rows.length && <div className="console-empty">No messages match these filters.</div>}
          </div>
          <div className="console-foot">
            <span>{rows.length} shown · {source.length} buffered (newest 800 kept) · {inCount} incoming</span>
            {paused && <Badge tone="warn">PAUSED</Badge>}
          </div>
        </section>

        <aside className="console-side">
          <section className="panel-card cut-card">
            <div className="kicker kicker-accent">// PAYLOAD</div>
            {sel ? (
              <div className="payload">
                <dl className="kv">
                  <div><dt>Time</dt><dd>{new Date(sel.at).toLocaleString()} <span className="tabnum">.{String(sel.at % 1000).padStart(3, '0')}</span></dd></div>
                  <div><dt>Direction</dt><dd>{sel.direction === 'in' ? '↓ Device → platform' : '↑ Dashboard → device'}</dd></div>
                  <div><dt>Device</dt><dd>{devName(sel.deviceId)}</dd></div>
                  <div><dt>Type</dt><dd>{KIND_LABEL[sel.kind]}</dd></div>
                  <div><dt>QoS / retain</dt><dd>{sel.qos} / {sel.retain ? 'yes' : 'no'}</dd></div>
                  <div><dt>Status</dt><dd><span className={cn('msg-status', `st-${sel.status}`)}>{sel.status}</span></dd></div>
                </dl>
                <div className="topic-parts" aria-label="Topic segments">
                  {sel.topic.split('/').map((p, i) => <span key={i}>{p}</span>)}
                </div>
                <pre className="payload-view">{prettyJson(sel.payload)}</pre>
                <Button size="sm" icon="LuCopy" onClick={() => {
                  navigator.clipboard?.writeText(`${sel.topic}\n${sel.payload}`).then(() => toast('Copied topic and payload', 'success'), () => toast('Copy is blocked here — select the text instead.', 'error'));
                }}>Copy</Button>
              </div>
            ) : (
              <p className="muted small">Select a message to inspect its topic and payload.</p>
            )}
          </section>

          <section className="panel-card cut-card">
            <div className="kicker kicker-accent">// PUBLISH TEST MESSAGE</div>
            <form className="form-grid" onSubmit={(e) => {
              e.preventDefault();
              const err = validateTopic(pubTopic);
              if (err) { setPubErr(err); return; }
              try { JSON.parse(pubPayload); } catch { setPubErr('Payload must be valid JSON, e.g. {"value": true}.'); return; }
              setPubErr('');
              void publishRaw(pubTopic, pubPayload).then((ok) => { if (ok) toast('Message published', 'success'); });
            }}>
              <Field label="Topic" htmlFor="pub-topic" error={pubErr} tip="Publishing to a simulated device's command topic makes it act and acknowledge, just like a dashboard control.">
                <input id="pub-topic" className="input mono" list="cmd-topics" value={pubTopic} placeholder="kokoon/devices/esp32-s3-demo-01/command/led_state" onChange={(e) => { setPubTopic(e.target.value); setPubErr(''); }} />
                <datalist id="cmd-topics">{Array.from(new Set(commandTopics)).map((t) => <option key={t} value={t} />)}</datalist>
              </Field>
              <Field label="Payload (JSON)" htmlFor="pub-payload">
                <textarea id="pub-payload" className="input mono" rows={3} value={pubPayload} onChange={(e) => setPubPayload(e.target.value)} />
              </Field>
              <Button type="submit" variant="dark" icon="LuArrowUpRight">Publish</Button>
              <p className="muted small">Commands use the proposed convention <InfoTip text="{device prefix}/command/{variable}. You can publish to your own devices’ topics; free-form topics need the Developer role. The LMS MQTT block defines the real topics." /></p>
            </form>
          </section>
        </aside>
      </div>
    </main>
  );
}
